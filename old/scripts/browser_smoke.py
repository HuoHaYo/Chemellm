"""Exercise the real UI against a running local service; creates clearly named QA artifacts."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/"data"/"qa"
OUT.mkdir(parents=True,exist_ok=True)

def main():
    with sync_playwright() as p:
        browser=p.chromium.launch(channel="msedge",headless=True)
        page=browser.new_page(viewport={"width":1440,"height":1080})
        errors=[]
        page.on("pageerror",lambda error:errors.append(str(error)))
        page.goto("http://127.0.0.1:8000")
        expect(page.locator("#chat-form")).to_be_visible()
        # Isolate every run through the same create-project UI used by a person.
        import time
        project_name="界面验证 · "+str(time.time_ns())
        page.locator("#new-project").click()
        page.locator('#new-project-form input[name="name"]').fill(project_name)
        page.locator("#new-project-form button").click()
        expect(page.locator("#project-name")).to_have_text(project_name)
        expect(page.locator("#chat-form")).to_be_visible()
        page.locator("#project-overview-button").click()
        page.locator('.resource-project-actions > summary').click()
        page.locator('#project-dialog [data-action="import"]').click()
        expect(page.locator('#project-dialog [data-navigate="acceptance"]')).to_contain_text("/ 31",timeout=20000)
        page.locator('[data-close-resources]').click()
        page.screenshot(path=str(OUT/"workspace.png"),full_page=True)
        page.locator('[data-page="tools"]').click()
        page.locator("#tool-picker").select_option("material_balance")
        page.locator("#calculate-button").click()
        expect(page.locator("#tool-result")).to_contain_text('"passed": true',timeout=20000)
        page.screenshot(path=str(OUT/"calculation.png"),full_page=True)
        page.locator("#tool-picker").select_option("heat_exchanger")
        page.locator('input[name="cold_out_C"]').fill("250")
        page.locator("#calculate-button").click()
        expect(page.locator("#tool-result")).to_contain_text("温差必须大于零")
        for name,expected in [
            ("reaction_thermo",'"equilibrium_feasible": true'),
            ("distillation_shortcut",'"minimum_stages"'),
            ("pipe_pressure_drop",'"Darcy_friction_factor"'),
            ("pinch_analysis",'"minimum_cold_utility_kW": 140')
        ]:
            page.locator("#tool-picker").select_option(name)
            page.locator("#calculate-button").click()
            expect(page.locator("#tool-result")).to_contain_text(expected,timeout=20000)
        page.locator("#tool-picker").select_option("aqueous_flash")
        page.locator("#calculate-button").click()
        expect(page.locator("#tool-result")).to_contain_text('"aqueous_liquid"',timeout=20000)
        expect(page.locator("#tool-result")).to_contain_text('"organic_liquid"')
        page.locator("#tool-picker").select_option("column_mesh")
        page.locator("#calculate-button").click()
        expect(page.locator("#tool-result tbody tr")).to_have_count(10,timeout=30000)
        expect(page.locator("#tool-result")).to_contain_text("再沸器供热")
        page.screenshot(path=str(OUT/"column-profile.png"),full_page=True)
        page.locator("#tool-picker").select_option("frontend_process")
        page.locator("#calculate-button").click()
        expect(page.locator("#tool-result tbody tr")).to_have_count(5,timeout=30000)
        expect(page.locator("#tool-result")).to_contain_text("含溶解有机物的水相")
        expect(page.locator("#tool-result")).to_contain_text("冷凝移热")
        page.screenshot(path=str(OUT/"frontend-streams.png"),full_page=True)
        page.locator("#tool-picker").select_option("wet_column")
        page.locator('input[name="equilibrium_stages"]').fill("6")
        page.locator('input[name="feed_stage"]').fill("3")
        page.locator("#calculate-button").click()
        expect(page.locator("[data-wet-outlets] tbody tr")).to_have_count(4,timeout=60000)
        expect(page.locator("[data-wet-stages] tbody tr")).to_have_count(6)
        expect(page.locator("#tool-result")).to_contain_text("塔顶水相")
        page.locator("#tool-picker").select_option("wet_separation_train")
        page.locator("#calculate-button").click()
        expect(page.locator("[data-streams] tbody tr")).to_have_count(9,timeout=90000)
        expect(page.locator("[data-wet-stages] tbody tr")).to_have_count(12)
        expect(page.locator("#tool-result")).to_contain_text("未验收产品")
        expect(page.locator("#tool-result")).not_to_contain_text("NaN")
        page.screenshot(path=str(OUT/"wet-train-streams.png"),full_page=True)
        page.locator("#tool-picker").select_option("recycle_process")
        page.locator("#calculate-button").click()
        expect(page.locator("[data-streams] tbody tr")).to_have_count(13,timeout=180000)
        expect(page.locator("[data-wet-stages] tbody tr")).to_have_count(50)
        expect(page.locator("[data-product-quality]")).to_contain_text("99.9002")
        expect(page.locator("[data-streams]")).to_contain_text("循环排放")
        expect(page.locator("[data-streams]")).to_contain_text("外部进料")
        expect(page.locator("#tool-result")).not_to_contain_text("NaN")
        page.screenshot(path=str(OUT/"recycle-streams.png"),full_page=True)
        page.locator("#tool-picker").select_option("export_report")
        page.locator('input[name="title"]').fill("界面验证·设计记录")
        page.locator('textarea[name="body"]').fill("界面测试文档。\n状态：未完成工程设计。\n苯乙烯物料衡算已通过工具数学闭合；尚需反应动力学、热量衡算与实际设计依据。")
        page.locator('textarea[name="formats"]').fill('["pdf","docx","pptx"]')
        page.locator("#calculate-button").click()
        expect(page.locator("#tool-result")).to_contain_text('"status": "draft"',timeout=30000)
        page.locator('[data-page="files"]').click()
        page.locator('[data-action="diagram"]').click()
        expect(page.locator("#preview-dialog")).to_be_visible(timeout=20000)
        frame=page.frame_locator("#preview-frame")
        expect(frame.locator("svg")).to_be_visible()
        page.screenshot(path=str(OUT/"pfd-preview.png"),full_page=True)
        page.locator('[data-close="preview-dialog"]').click()
        svg_card=page.locator(".file-card").filter(has=page.locator(".file-art",has_text="SVG"))
        svg_card.get_by_role("button",name="识读",exact=True).click()
        expect(page.locator("#tool-result")).to_contain_text('"encoded_unverified"',timeout=20000)
        page.locator('[data-edit-topology]').click()
        expect(page.locator("#tool-picker")).to_have_value("pfd")
        topology=json.loads(page.locator('textarea[name="_json"]').input_value())
        topology["title"]="界面验证·编辑后拓扑"
        page.locator('textarea[name="_json"]').fill(json.dumps(topology,ensure_ascii=False))
        page.locator("#calculate-button").click()
        expect(page.locator("#tool-result")).to_contain_text(".dxf",timeout=20000)
        page.locator('[data-page="files"]').click()
        dxf_card=page.locator(".file-card").filter(has_text="界面验证·编辑后拓扑.dxf")
        download_url=dxf_card.get_by_role("link",name="下载 ↓").get_attribute("href")
        raw=page.request.get("http://127.0.0.1:8000"+download_url).body()
        page.locator("#upload").set_input_files({"name":"QA-roundtrip.dxf","mimeType":"application/dxf","buffer":raw})
        uploaded=page.locator(".file-card").filter(has_text="QA-roundtrip.dxf")
        expect(uploaded).to_be_visible(timeout=20000)
        uploaded.get_by_role("button",name="打开预览 ↗").click()
        expect(page.frame_locator("#preview-frame").locator("svg")).to_be_visible()
        expect(page.frame_locator("#preview-frame").locator("svg")).to_contain_text("脱氢反应器")
        page.screenshot(path=str(OUT/"dxf-preview.png"),full_page=True)
        page.locator('[data-close="preview-dialog"]').click()
        uploaded.get_by_role("button",name="识读",exact=True).click()
        expect(page.locator("#tool-result")).to_contain_text("界面验证·编辑后拓扑",timeout=20000)
        page.locator('[data-page="files"]').click()
        page.locator(".file-card").filter(has_text="界面验证·设计记录.docx").get_by_role("button",name="打开预览").click()
        expect(page.frame_locator("#preview-frame").locator("body")).to_contain_text("界面测试文档")
        page.locator('[data-close="preview-dialog"]').click()
        page.locator('[data-page="acceptance"]').click()
        expect(page.locator("tbody tr")).to_have_count(35)
        page.locator('[data-requirement="P04"]').click()
        page.locator('#requirement-form select[name="status"]').select_option("draft")
        options=page.locator('#requirement-form select[name="evidence"] option').all()
        target=next(o.get_attribute("value") for o in options if ".svg" in o.inner_text())
        page.locator('#requirement-form select[name="evidence"]').select_option(target)
        page.locator('#requirement-form textarea[name="notes"]').fill("概念流程图已生成，尚需工程校核与完善物流表。")
        page.locator("#requirement-form button").click()
        expect(page.locator("tr").filter(has_text="P04")).to_contain_text("已有草稿")
        page.locator('[data-page="database"]').click()
        expect(page.locator("#content")).to_contain_text("48000")
        page.locator('[data-action="equipment-new"]').click()
        form=page.locator("#equipment-form")
        tag="E-QA"+str(__import__("time").time_ns())[-9:]
        form.locator('input[name="tag"]').fill(tag)
        form.locator('input[name="name"]').fill("界面验证换热器")
        form.locator('[data-param="label"]').fill("设计压力")
        form.locator('[data-param="name"]').fill("design_pressure")
        form.locator('[data-param="value"]').fill("3")
        form.locator('[data-param="unit"]').fill("bar")
        form.locator('[type="submit"]').click()
        row=page.locator("#equipment-panel tr").filter(has_text=tag)
        expect(row).to_contain_text("v1")
        row.get_by_role("button",name="编辑",exact=True).click()
        page.locator('#equipment-form [data-param="value"]').fill("4")
        page.locator('#equipment-form [type="submit"]').click()
        expect(page.locator("#equipment-panel tr").filter(has_text=tag)).to_contain_text("v2")
        page.locator("#equipment-panel tr").filter(has_text=tag).get_by_role("button",name="版本历史").click()
        expect(page.locator("#form-body")).to_contain_text("v1")
        expect(page.locator("#form-body")).to_contain_text("v2")
        page.locator('[data-close="form-dialog"]').click()
        page.screenshot(path=str(OUT/"equipment-database.png"),full_page=True)
        page.locator('[data-page="workspace"]').click()
        expect(page.locator("#chat-form")).to_be_visible()
        page.set_viewport_size({"width":390,"height":844})
        page.screenshot(path=str(OUT/"mobile.png"),full_page=True)
        assert page.evaluate("document.documentElement.scrollWidth <= window.innerWidth"),"mobile horizontal overflow"
        assert not errors,errors
        browser.close()
        result={"browser":"Microsoft Edge headless","passed":True,"errors":errors,"checks":["competition import","material balance","invalid temperature rejection","reaction heat and equilibrium","distillation shortcut","MESH profile table","connected reactor/condenser stream table","wet column four outlets and six-stage profile","connected wet train nine streams and twelve-stage profile","four-component recycle thirteen streams and fifty-stage profile","mass purity target comparison and external boundaries","UNIFAC aqueous/organic flash","pipe pressure loss","pinch stream JSON example","DOCX/PPTX/PDF export","SVG preview and reading","topology edit and regenerate","DXF download/upload/preview/read","DOCX text preview","acceptance evidence update","equipment create/edit/history","database","mobile width"]}
        (OUT/"browser-results.json").write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding="utf-8")
        print(json.dumps(result,ensure_ascii=False))

if __name__=="__main__":
    main()
